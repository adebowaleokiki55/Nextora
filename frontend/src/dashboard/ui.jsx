/* Small shared UI pieces for the command centre. */

import { RISK_STYLES } from "./format";

export function Card({ title, subtitle, actions, children, className = "" }) {
  return (
    <section className={`rounded-2xl bg-white shadow-sm ring-1 ring-slate-200 ${className}`}>
      {(title || actions) && (
        <header className="flex items-start justify-between gap-3 border-b border-slate-100 px-4 py-3">
          <div>
            <h2 className="text-sm font-bold text-slate-900">{title}</h2>
            {subtitle && <p className="mt-0.5 text-xs text-slate-500">{subtitle}</p>}
          </div>
          {actions && <div className="flex shrink-0 items-center gap-2">{actions}</div>}
        </header>
      )}
      <div className="p-4">{children}</div>
    </section>
  );
}

export function OriginBadge({ origin }) {
  if (!origin) return null;
  if (origin === "REAL") {
    return (
      <span className="inline-flex items-center rounded-full bg-emerald-50 px-2 py-0.5 text-[10px] font-bold tracking-wide text-emerald-700 ring-1 ring-emerald-200">
        REAL
      </span>
    );
  }
  return (
    <span
      title="Demo data generated by Nextora, not real-world observations"
      className="inline-flex items-center rounded-full border border-dashed border-amber-500 bg-amber-50 px-2 py-0.5 text-[10px] font-bold tracking-wide text-amber-800"
    >
      {origin === "MIXED" ? "MIXED" : "SYNTHETIC"}
    </span>
  );
}

export function RiskChip({ level, score }) {
  const style = RISK_STYLES[level] || RISK_STYLES.UNKNOWN;
  return (
    <span className={`inline-flex items-center gap-1 rounded-full px-2 py-0.5 text-xs font-semibold ring-1 ${style.chip}`}>
      {style.label}
      {score !== null && score !== undefined && <span className="font-bold">{Math.round(score)}</span>}
    </span>
  );
}

export function Pill({ className = "", children }) {
  return (
    <span className={`inline-flex items-center rounded-md px-1.5 py-0.5 text-[10px] font-bold uppercase tracking-wide ${className}`}>
      {children}
    </span>
  );
}

export function Button({ variant = "primary", className = "", ...props }) {
  const styles = {
    primary: "bg-emerald-700 text-white hover:bg-emerald-800",
    secondary: "bg-white text-slate-700 ring-1 ring-slate-300 hover:bg-slate-50",
    danger: "bg-white text-red-700 ring-1 ring-red-200 hover:bg-red-50",
    ghost: "text-slate-600 hover:bg-slate-100",
  };
  return (
    <button
      type="button"
      className={`inline-flex items-center justify-center gap-1.5 rounded-lg px-3 py-1.5 text-xs font-semibold transition ${styles[variant]} ${className}`}
      {...props}
    />
  );
}

export function ErrorNote({ error }) {
  if (!error) return null;
  return <p className="rounded-lg bg-red-50 px-3 py-2 text-xs text-red-700">{error}</p>;
}

export function Empty({ children }) {
  return <p className="py-6 text-center text-xs text-slate-400">{children}</p>;
}
