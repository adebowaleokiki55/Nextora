"""SYNTHETIC weekly malaria case counts driven by weather.

Public weekly case data per Lagos LGA is not available, so the demo uses
generated counts. They are always stored with data_origin=SYNTHETIC.

Model (deliberately simple and documented):
    expected = base(LGA) x year_factor x rain_effect x temp_effect x scenario
    cases    ~ Poisson(expected x Gamma noise)    (overdispersed counts)

- rain_effect: rainfall summed over the previous 3-8 weeks (the lag for
  mosquito breeding plus parasite development), saturating via log1p.
- temp_effect: a broad bell curve around 25 °C, near the reported optimum
  for P. falciparum transmission.
- scenario: the scripted demo story (Ikorodu rising in the latest weeks).
"""

from __future__ import annotations

from dataclasses import dataclass

import numpy as np
import pandas as pd

from backend.app.core.surveillance.metrics import CASES, RAINFALL, TEMP_MEAN

SOURCE = (
    "SYNTHETIC: generated by Nextora from weekly weather (lagged rainfall and "
    "temperature) with a scripted demo scenario; not real surveillance data"
)

RAIN_LAG_MIN = 3
RAIN_LAG_MAX = 8


@dataclass(frozen=True)
class Scenario:
    """A scripted surge: cases in `location` multiplied up over the last weeks."""

    location: str = "Ikorodu"
    weeks: int = 6
    peak_multiplier: float = 1.9


def _base_level(names: list[str], rng: np.random.Generator) -> dict[str, float]:
    levels = {name: float(rng.uniform(35, 140)) for name in sorted(names)}
    # A few large, peri-urban LGAs carry more cases in the scenario.
    for name, level in {"Alimosho": 170.0, "Ikorodu": 130.0, "Epe": 95.0, "Badagry": 90.0}.items():
        if name in levels:
            levels[name] = level
    return levels


def lagged_rain(rain: pd.Series) -> pd.Series:
    """Sum of rainfall from RAIN_LAG_MIN to RAIN_LAG_MAX weeks ago."""
    window = RAIN_LAG_MAX - RAIN_LAG_MIN + 1
    return rain.shift(RAIN_LAG_MIN).rolling(window, min_periods=window).sum()


def generate_cases(
    weekly_weather: pd.DataFrame,
    scenario: Scenario | None = Scenario(),
    seed: int = 2026,
) -> pd.DataFrame:
    """Return rows (location, week_start, malaria_cases_confirmed, expected)."""
    rng = np.random.default_rng(seed)
    names = sorted(weekly_weather["location"].unique())
    base = _base_level(names, rng)
    frames = []

    for name in names:
        weather = (
            weekly_weather[weekly_weather["location"] == name]
            .sort_values("week_start")
            .reset_index(drop=True)
        )
        rain_lagged = lagged_rain(weather[RAINFALL])
        typical_rain = rain_lagged.median()
        rain_effect = np.log1p(rain_lagged / 25.0) / np.log1p(typical_rain / 25.0)
        rain_effect = (0.45 + 0.55 * rain_effect).clip(lower=0.35)

        temp_lagged = weather[TEMP_MEAN].shift(2).rolling(4, min_periods=4).mean()
        temp_effect = np.exp(-((temp_lagged - 25.0) ** 2) / (2 * 4.5**2))
        temp_effect = temp_effect / temp_effect.median()

        years = pd.to_datetime(weather["week_start"]).dt.year
        year_factor = years.map({y: rng.gamma(40, 1 / 40) for y in sorted(years.unique())})

        expected = base[name] * year_factor * rain_effect * temp_effect

        if scenario is not None and name == scenario.location:
            ramp = np.ones(len(weather))
            steps = min(scenario.weeks, len(weather))
            ramp[len(weather) - steps:] = np.linspace(
                1 + (scenario.peak_multiplier - 1) / steps, scenario.peak_multiplier, steps
            )
            expected = expected * ramp

        valid = expected.notna()
        noise = rng.gamma(25, 1 / 25, size=int(valid.sum()))
        cases = pd.Series(np.nan, index=weather.index)
        cases[valid] = rng.poisson(expected[valid].to_numpy() * noise)

        frames.append(
            pd.DataFrame(
                {
                    "location": name,
                    "week_start": weather["week_start"],
                    CASES: cases,
                    "expected": expected.round(2),
                }
            )[valid]
        )

    result = pd.concat(frames, ignore_index=True)
    result[CASES] = result[CASES].astype(int)
    return result
